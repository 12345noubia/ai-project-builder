/** Builds bilingual (EN/FR) debug reports as PDF or Word, embedding canvas snapshots. Browser-only. */
export type ReportLang = "en" | "fr";
export interface ReportStep { title: string; kind: string; status: "ok" | "stop" | "fail"; note: string; explanation?: string | undefined; image?: string | undefined }
export interface ReportData {
  workflow: string; project?: string | undefined; persona: string; lang: ReportLang; date: Date;
  overview?: string | undefined; steps: ReportStep[];
  summary?: string | undefined; rootCause?: string | undefined; recommendations?: string[] | undefined; patch?: string | undefined;
}

const T = {
  en: { title: "Workflow Debug Report", by: "Generated by Opero", wf: "Workflow", persona: "Virtual user", date: "Date", steps: "Steps executed", passed: "Passed", failed: "Failed", stopped: "Stopped",
    result: "Result", success: "Success", failure: "Issues found", exec: "Executive summary", overview: "Flow overview", detail: "Step-by-step walkthrough", step: "Step", status: "Status",
    root: "Root cause analysis", recs: "Recommendations", patch: "Suggested fix", noAi: "Run the AI diagnosis in Opero to include an expert summary.", type: "Type", page: "Page",
    defaultSummary: (n: number, f: number) => `The virtual user executed ${n} steps. ${f ? `${f} step(s) failed and need attention.` : "Every step completed as expected."}` },
  fr: { title: "Rapport de débogage du workflow", by: "Généré par Opero", wf: "Workflow", persona: "Utilisateur virtuel", date: "Date", steps: "Étapes exécutées", passed: "Réussies", failed: "Échouées", stopped: "Arrêtées",
    result: "Résultat", success: "Succès", failure: "Problèmes détectés", exec: "Résumé exécutif", overview: "Vue d'ensemble du flux", detail: "Parcours étape par étape", step: "Étape", status: "Statut",
    root: "Analyse de la cause racine", recs: "Recommandations", patch: "Correctif suggéré", noAi: "Lancez le diagnostic IA dans Opero pour inclure un résumé d'expert.", type: "Type", page: "Page",
    defaultSummary: (n: number, f: number) => `L'utilisateur virtuel a exécuté ${n} étapes. ${f ? `${f} étape(s) ont échoué et nécessitent une attention.` : "Toutes les étapes se sont déroulées comme prévu."}` },
};

const statusLabel = (l: ReportLang, s: ReportStep["status"]) => (s === "ok" ? T[l].passed : s === "fail" ? T[l].failed : T[l].stopped);

function stats(d: ReportData) {
  const f = d.steps.filter((s) => s.status === "fail").length;
  return { n: d.steps.length, f, ok: d.steps.filter((s) => s.status === "ok").length, stop: d.steps.filter((s) => s.status === "stop").length };
}

function imgSize(src: string): Promise<{ w: number; h: number }> {
  return new Promise((res) => { const i = new Image(); i.onload = () => res({ w: i.naturalWidth, h: i.naturalHeight }); i.onerror = () => res({ w: 1, h: 1 }); i.src = src; });
}

function download(blob: Blob, name: string) {
  const a = document.createElement("a"); a.href = URL.createObjectURL(blob); a.download = name; a.click();
  setTimeout(() => URL.revokeObjectURL(a.href), 4000);
}

const fileBase = (d: ReportData) => `${d.workflow.replace(/[^\w-]+/g, "_")}_debug_${d.lang}`;

export async function downloadPdf(d: ReportData) {
  const { jsPDF } = await import("jspdf");
  const t = T[d.lang]; const s = stats(d);
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth(); const H = doc.internal.pageSize.getHeight(); const M = 48;
  const brand: [number, number, number] = [109, 40, 217];
  let y = 0;
  const footer = () => {
    const pages = doc.getNumberOfPages();
    for (let p = 1; p <= pages; p++) {
      doc.setPage(p); doc.setFontSize(8); doc.setTextColor(140);
      doc.text(`${t.by} · ${d.workflow}`, M, H - 24); doc.text(`${t.page} ${p} / ${pages}`, W - M, H - 24, { align: "right" });
    }
  };
  const ensure = (h: number) => { if (y + h > H - 50) { doc.addPage(); y = M; } };
  const heading = (txt: string) => { ensure(40); doc.setFont("helvetica", "bold"); doc.setFontSize(15); doc.setTextColor(...brand); doc.text(txt, M, y); y += 8; doc.setDrawColor(...brand); doc.setLineWidth(1); doc.line(M, y, M + 40, y); y += 18; };
  const para = (txt: string, size = 10.5, color = 50) => {
    doc.setFont("helvetica", "normal"); doc.setFontSize(size); doc.setTextColor(color);
    for (const line of doc.splitTextToSize(txt, W - 2 * M) as string[]) { ensure(16); doc.text(line, M, y); y += size * 1.45; }
    y += 6;
  };
  const image = async (src: string | undefined, maxH: number) => {
    if (!src) return;
    const { w, h } = await imgSize(src); const scale = Math.min((W - 2 * M) / w, maxH / h, 1.2);
    ensure(h * scale + 10); doc.setDrawColor(225); doc.roundedRect(M - 1, y - 1, w * scale + 2, h * scale + 2, 4, 4);
    doc.addImage(src, "PNG", M, y, w * scale, h * scale); y += h * scale + 14;
  };

  // Cover
  doc.setFillColor(...brand); doc.rect(0, 0, W, 230, "F");
  doc.setTextColor(255); doc.setFont("helvetica", "bold"); doc.setFontSize(11); doc.text("OPERO", M, 60);
  doc.setFontSize(28); doc.text(doc.splitTextToSize(t.title, W - 2 * M) as string[], M, 120);
  doc.setFont("helvetica", "normal"); doc.setFontSize(13); doc.text(d.workflow, M, 190);
  y = 280;
  const rows: [string, string][] = [[t.wf, d.workflow], [t.persona, d.persona], [t.date, d.date.toLocaleString(d.lang === "fr" ? "fr-FR" : "en-GB")], [t.steps, String(s.n)], [t.result, s.f ? t.failure : t.success]];
  for (const [k, v] of rows) { doc.setFontSize(10); doc.setTextColor(120); doc.text(k.toUpperCase(), M, y); doc.setTextColor(30); doc.setFontSize(12); doc.text(v, M + 150, y); y += 26; }
  y += 10;
  const cards: [string, number, [number, number, number]][] = [[t.passed, s.ok, [22, 163, 74]], [t.failed, s.f, [220, 38, 38]], [t.stopped, s.stop, [217, 119, 6]]];
  const cw = (W - 2 * M - 24) / 3;
  cards.forEach(([l, v, c], i) => { const x = M + i * (cw + 12); doc.setFillColor(248, 247, 252); doc.roundedRect(x, y, cw, 70, 8, 8, "F"); doc.setTextColor(...c); doc.setFont("helvetica", "bold"); doc.setFontSize(24); doc.text(String(v), x + 14, y + 36); doc.setFontSize(9); doc.setTextColor(110); doc.setFont("helvetica", "normal"); doc.text(l, x + 14, y + 56); });
  y += 100;

  heading(t.exec); para(d.summary || t.defaultSummary(s.n, s.f)); if (!d.summary) para(t.noAi, 9, 130);
  doc.addPage(); y = M;
  heading(t.overview); await image(d.overview, 360);
  heading(t.detail);
  for (const [i, st] of d.steps.entries()) {
    ensure(60);
    const c: [number, number, number] = st.status === "fail" ? [220, 38, 38] : st.status === "stop" ? [217, 119, 6] : [22, 163, 74];
    doc.setFillColor(...c); doc.circle(M + 9, y - 4, 9, "F"); doc.setTextColor(255); doc.setFontSize(9); doc.setFont("helvetica", "bold"); doc.text(String(i + 1), M + 9, y - 1, { align: "center" });
    doc.setTextColor(30); doc.setFontSize(12); doc.text(`${t.step} ${i + 1} — ${st.title}`, M + 26, y);
    y += 16; doc.setFont("helvetica", "normal"); doc.setFontSize(9); doc.setTextColor(...c); doc.text(`${t.status}: ${statusLabel(d.lang, st.status)}   ·   ${t.type}: ${st.kind}`, M + 26, y); y += 16;
    await image(st.image, 120);
    para(st.explanation || st.note);
    y += 4;
  }
  if (d.rootCause || d.recommendations?.length) {
    heading(t.root); para(d.rootCause || "-");
    heading(t.recs); (d.recommendations ?? []).forEach((r, i) => para(`${i + 1}. ${r}`));
  }
  if (d.patch) {
    heading(t.patch);
    doc.setFont("courier", "normal"); doc.setFontSize(8.5); doc.setTextColor(40);
    for (const line of doc.splitTextToSize(d.patch, W - 2 * M - 16) as string[]) { ensure(12); doc.setFillColor(246, 245, 250); doc.rect(M, y - 9, W - 2 * M, 12, "F"); doc.text(line, M + 8, y); y += 12; }
  }
  footer();
  download(doc.output("blob"), `${fileBase(d)}.pdf`);
}

function dataUrlBytes(src: string) {
  const b = atob(src.split(",")[1] ?? ""); const u = new Uint8Array(b.length);
  for (let i = 0; i < b.length; i++) u[i] = b.charCodeAt(i);
  return u;
}

export async function downloadDocx(d: ReportData) {
  const x = await import("docx");
  const t = T[d.lang]; const s = stats(d);
  const BRAND = "6D28D9";
  const H = (text: string) => new x.Paragraph({ heading: x.HeadingLevel.HEADING_1, spacing: { before: 360, after: 160 }, children: [new x.TextRun({ text, color: BRAND, bold: true })] });
  const P = (text: string, opts: { color?: string; size?: number; italics?: boolean } = {}) => new x.Paragraph({ spacing: { after: 140 }, children: [new x.TextRun({ text, ...opts })] });
  const img = async (src: string | undefined, maxW: number) => {
    if (!src) return [];
    const { w, h } = await imgSize(src); const sc = Math.min(maxW / w, 1);
    return [new x.Paragraph({ spacing: { after: 160 }, children: [new x.ImageRun({ type: "png", data: dataUrlBytes(src), transformation: { width: Math.round(w * sc), height: Math.round(h * sc) } })] })];
  };
  const cell = (text: string, bold = false, fill?: string) => new x.TableCell({ shading: fill ? { fill } : undefined, margins: { top: 80, bottom: 80, left: 120, right: 120 }, children: [new x.Paragraph({ children: [new x.TextRun({ text, bold })] })] });
  const summaryTable = new x.Table({
    width: { size: 100, type: x.WidthType.PERCENTAGE },
    rows: ([[t.wf, d.workflow], [t.persona, d.persona], [t.date, d.date.toLocaleString(d.lang === "fr" ? "fr-FR" : "en-GB")], [t.steps, String(s.n)], [t.passed, String(s.ok)], [t.failed, String(s.f)], [t.result, s.f ? t.failure : t.success]] as [string, string][])
      .map(([k, v]) => new x.TableRow({ children: [cell(k, true, "F3F0FB"), cell(v)] })),
  });
  const children: (InstanceType<typeof x.Paragraph> | InstanceType<typeof x.Table>)[] = [
    new x.Paragraph({ children: [new x.TextRun({ text: "OPERO", bold: true, color: BRAND, size: 22 })] }),
    new x.Paragraph({ heading: x.HeadingLevel.TITLE, spacing: { after: 120 }, children: [new x.TextRun({ text: t.title, bold: true, size: 52 })] }),
    P(d.workflow, { size: 28, color: "555555" }),
    summaryTable,
    H(t.exec), P(d.summary || t.defaultSummary(s.n, s.f)), ...(d.summary ? [] : [P(t.noAi, { italics: true, color: "888888" })]),
    H(t.overview), ...(await img(d.overview, 600)),
    H(t.detail),
  ];
  for (const [i, st] of d.steps.entries()) {
    const color = st.status === "fail" ? "DC2626" : st.status === "stop" ? "D97706" : "16A34A";
    children.push(new x.Paragraph({ heading: x.HeadingLevel.HEADING_2, spacing: { before: 240, after: 80 }, children: [new x.TextRun({ text: `${t.step} ${i + 1} — ${st.title}` })] }));
    children.push(P(`${t.status}: ${statusLabel(d.lang, st.status)}  ·  ${t.type}: ${st.kind}`, { color, size: 18 }));
    children.push(...(await img(st.image, 320)));
    children.push(P(st.explanation || st.note));
  }
  if (d.rootCause || d.recommendations?.length) {
    children.push(H(t.root), P(d.rootCause || "-"), H(t.recs));
    (d.recommendations ?? []).forEach((r) => children.push(new x.Paragraph({ bullet: { level: 0 }, children: [new x.TextRun(r)] })));
  }
  if (d.patch) {
    children.push(H(t.patch));
    d.patch.split("\n").forEach((l) => children.push(new x.Paragraph({ shading: { fill: "F6F5FA" }, children: [new x.TextRun({ text: l || " ", font: "Consolas", size: 18 })] })));
  }
  const doc = new x.Document({
    creator: "Opero", title: `${t.title} — ${d.workflow}`,
    sections: [{
      footers: { default: new x.Footer({ children: [new x.Paragraph({ alignment: x.AlignmentType.CENTER, children: [new x.TextRun({ text: `${t.by} · `, color: "888888", size: 16 }), new x.TextRun({ children: [x.PageNumber.CURRENT], color: "888888", size: 16 })] })] }) },
      children,
    }],
  });
  download(await x.Packer.toBlob(doc), `${fileBase(d)}.docx`);
}
